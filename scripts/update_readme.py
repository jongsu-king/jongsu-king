#!/usr/bin/env python3
"""Rewrite the software table in README.md from the account's public repositories.

Every public repository that isn't a fork, archived, empty or this profile repository gets a
row, so a new one shows up without anyone touching the README. scripts/projects.json holds
the wording for the projects written up by hand and fixes their order. Any other repository
goes at the bottom, oldest first, described by its GitHub description or, failing that, the
first paragraph of its README. Add a repository's name to "hidden" to leave it out.

The DOI comes from the top-level doi field of CITATION.cff, and the Download link appears
when the latest release has files attached. Badges are written to OUTPUT_DIR and served from
the output branch instead of zenodo.org, whose badges are slow enough to show up broken.

The table has one column because a phone can't fit two: a long unbreakable formula in the
second column would push the first one out of view.

Usage: GH_TOKEN=... update_readme.py USER README_PATH OUTPUT_DIR   (standard library only)
"""
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

QUERY = """
query($login: String!) {
  user(login: $login) {
    repositories(first: 100, privacy: PUBLIC, isFork: false, ownerAffiliations: OWNER,
                 orderBy: {field: CREATED_AT, direction: ASC}) {
      nodes {
        name
        description
        isArchived
        isEmpty
        latestRelease { releaseAssets { totalCount } }
        citation: object(expression: "HEAD:CITATION.cff") { ... on Blob { text } }
        readme: object(expression: "HEAD:README.md") { ... on Blob { text } }
      }
    }
  }
}
"""
START = "<!-- repos:start: generated by scripts/update_readme.py. Edit scripts/projects.json, not this table. -->"
END = "<!-- repos:end -->"
HEADER = "| Project |\n|:---|"
MAX_BLURB = 220


def fetch(user):
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=json.dumps({"query": QUERY, "variables": {"login": user}}).encode(),
        headers={"Authorization": f"bearer {os.environ['GH_TOKEN']}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        payload = json.load(resp)
    if payload.get("errors"):
        raise SystemExit(f"GraphQL error: {payload['errors']}")
    return payload["data"]["user"]["repositories"]["nodes"]


def first_paragraph(markdown):
    """The first run of plain text lines, skipping headings, badges, HTML, tables, lists and code."""
    lines, in_code = [], False
    for line in markdown.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        if not stripped:
            if lines:
                break
            continue
        if re.match(r"(#|!\[|\[!\[|<|\||>|[-*+] |\d+\. |---|===)", stripped):
            if lines:
                break
            continue
        lines.append(stripped)
    return " ".join(lines)


def shorten(text):
    if len(text) <= MAX_BLURB:
        return text
    return text[:MAX_BLURB].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def find_doi(repo):
    citation = (repo["citation"] or {}).get("text") or ""
    match = re.search(r"""^doi:\s*["']?([^\s"']+)""", citation, re.M)
    return match.group(1) if match else None


def blurb_for(repo, info):
    if "blurb" in info:
        return info["blurb"]
    text = (repo["description"] or "").strip() or first_paragraph((repo["readme"] or {}).get("text") or "")
    return shorten(text).replace("|", "\\|") or "—"


def badge_name(doi):
    return "doi-" + doi.replace("/", "-") + ".svg"


def badge_svg(doi):
    """The same flat badge zenodo.org draws, sized for the length of the DOI."""
    label, value = 31, round(len(doi) * 7.04)
    width = label + value
    shadowed = lambda x, s, extra="": (
        f'<text x="{x}" y="15" fill="#010101" fill-opacity=".3"{extra}>{s}</text><text x="{x}" y="14"{extra}>{s}</text>'
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="20" role="img" aria-label="DOI {doi}">'
        '<linearGradient id="b" x2="0" y2="100%"><stop offset="0" stop-color="#bbb" stop-opacity=".1"/><stop offset="1" stop-opacity=".1"/></linearGradient>'
        f'<mask id="a"><rect width="{width}" height="20" rx="3" fill="#fff"/></mask>'
        f'<g mask="url(#a)"><path fill="#555" d="M0 0h{label}v20H0z"/><path fill="#007ec6" d="M{label} 0h{value}v20H{label}z"/><path fill="url(#b)" d="M0 0h{width}v20H0z"/></g>'
        '<g fill="#fff" text-anchor="middle" font-family="DejaVu Sans,Verdana,Geneva,sans-serif" font-size="11">'
        + shadowed(16, "DOI")
        + shadowed(label + value / 2, doi, f' textLength="{value - 12}" lengthAdjust="spacingAndGlyphs"')
        + "</g></svg>\n"
    )


def row(user, repo, info):
    url = f"https://github.com/{user}/{repo['name']}"
    head = f"**[{info.get('title', repo['name'])}]({url})**"
    doi = find_doi(repo)
    if doi:
        src = f"https://raw.githubusercontent.com/{user}/{user}/output/{badge_name(doi)}"
        head += f' <a href="https://doi.org/{doi}"><img src="{src}" alt="DOI {doi}"></a>'
    release = repo["latestRelease"]
    if release and release["releaseAssets"]["totalCount"]:
        head += f" <small>[Download]({url}/releases/latest)</small>"
    return f"| {head}<br>{blurb_for(repo, info)} |"


def listed(user, repos, config):
    projects = config["projects"]
    shown = [
        r for r in repos
        if not r["isArchived"] and not r["isEmpty"] and r["name"] != user and r["name"] not in config["hidden"]
    ]
    known = {r["name"]: r for r in shown}
    ordered = [known[name] for name in projects if name in known]
    ordered += [r for r in shown if r["name"] not in projects]
    if not ordered:
        raise SystemExit("No repositories to list; leaving the README alone.")
    return ordered


def main(user, readme_path, out_dir):
    readme_path, out_dir = Path(readme_path), Path(out_dir)
    config = json.loads((Path(__file__).parent / "projects.json").read_text(encoding="utf-8"))
    readme = readme_path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pattern.search(readme):
        raise SystemExit("The README has no repos:start and repos:end markers.")
    repos = listed(user, fetch(user), config)
    out_dir.mkdir(parents=True, exist_ok=True)
    for doi in filter(None, map(find_doi, repos)):
        (out_dir / badge_name(doi)).write_text(badge_svg(doi), encoding="utf-8")
    rows = "\n".join(row(user, r, config["projects"].get(r["name"], {})) for r in repos)
    block = f"{START}\n\n{HEADER}\n{rows}\n\n{END}"
    updated = pattern.sub(lambda _: block, readme)
    if updated != readme:
        readme_path.write_text(updated, encoding="utf-8")
        print("README updated.")
    else:
        print("README unchanged.")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
