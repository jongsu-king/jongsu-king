#!/usr/bin/env python3
"""Generate the live stat cards from GitHub's GraphQL API, in the cards' amber style.

Every peak and bar is real data: nothing here is smoothed, padded or made up, and
private repositories are dropped by name even when the token could see them.

Usage: GH_TOKEN=... make_signal.py USER OUTPUT_DIR   (standard library only)
"""
import datetime as dt
import json
import math
import os
import sys
import urllib.request
from pathlib import Path

from make_cards import AMBER, DIM, MAJOR, TEXT, card, glow_trace, label

QUERY = """
query($login: String!) {
  user(login: $login) {
    contributionsCollection {
      contributionCalendar {
        totalContributions
        weeks { contributionDays { date contributionCount } }
      }
      commitContributionsByRepository(maxRepositories: 10) {
        repository { name isPrivate }
        contributions { totalCount }
      }
    }
    repositories(first: 100, privacy: PUBLIC, ownerAffiliations: OWNER, isFork: false) {
      nodes {
        languages(first: 10, orderBy: { field: SIZE, direction: DESC }) {
          edges { size node { name } }
        }
      }
    }
  }
}
"""


def fetch(user):
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=json.dumps({"query": QUERY, "variables": {"login": user}}).encode(),
        headers={"Authorization": f"bearer {os.environ['GH_TOKEN']}", "Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        payload = json.load(resp)
    if payload.get("errors"):
        raise SystemExit(f"GraphQL error: {payload['errors']}")
    return payload["data"]["user"]


def nice_max(value):
    for step in (1, 2, 5, 10, 20, 25, 50, 100, 200, 250, 500):
        top = math.ceil(value / step) * step
        if top / step <= 5:
            return top, step
    return value, value


def spectrum_card(path, calendar, today):
    x0, y0, x1, y1 = 56, 70, 1200, 262
    days = [d for week in calendar["weeks"] for d in week["contributionDays"]]
    active = [(dt.date.fromisoformat(d["date"]), d["contributionCount"]) for d in days if d["contributionCount"] > 0]
    first = active[0][0] if active else today
    start = max(today - dt.timedelta(days=365), min(first - dt.timedelta(days=10), today - dt.timedelta(days=90)))
    span = (today - start).days + 2
    per_day = (x1 - x0) / span
    fx = lambda d: x0 + ((d - start).days + 1) * per_day

    top_value, step = nice_max(max((c for _, c in active), default=1))
    base, ceiling = y1 - 22, y0 + 26
    fy = lambda v: base - v / top_value * (base - ceiling)

    # A narrow Gaussian per day: neighbours barely overlap, so peak heights stay true.
    sigma = max(1.1, per_day * 0.3)
    centres = [fx(d) for d, _ in active]
    samples = sorted({x0 + i * 0.5 for i in range(int((x1 - x0) * 2) + 1)} | set(centres))
    points = []
    for x in samples:
        v = sum(c * math.exp(-0.5 * ((x - fx(d)) / sigma) ** 2) for d, c in active if abs(x - fx(d)) < 6 * sigma)
        points.append((x, fy(v)))

    body = f'<path d="M{x0} {base} H{x1}" class="dimline"/>'
    for v in range(0, top_value + 1, step):
        body += f'<path d="M{x0} {fy(v):.1f} H{x1}" stroke="{MAJOR}"/>' + label(x0 + 6, fy(v) - 3, str(v), "ax", "start")
    month = dt.date(start.year, start.month, 1)
    while month <= today:
        if month >= start:
            body += f'<path d="M{fx(month):.1f} {base} v5" stroke="{DIM}"/>' + label(fx(month), base + 17, month.strftime("%b"), "ax")
        month = dt.date(month.year + (month.month == 12), month.month % 12 + 1, 1)
    body += glow_trace(points)

    placed = []
    for d, c in sorted(active, key=lambda item: -item[1]):
        x = fx(d)
        if len(placed) < 6 and all(abs(x - other) > 92 for other in placed):
            placed.append(x)
            body += label(x, fy(c) - 8, f"{d:%m-%d} · {c}")

    card(path, kick="LIVE SIGNAL", title="Contribution spectrum", right=f"UPDATED {today:%Y-%m-%d}",
         desc=[f"{calendar['totalContributions']} contributions across {len(active)} active days in the last year. Each peak is one day; its height is that day's count."],
         tags="GENERATED BY GITHUB ACTIONS FROM THE GRAPHQL API · NO SMOOTHING, NO PADDING",
         body=body, w=1224, h=346, plot=(x0 - 32, y0, x1, y1))


def composition_card(path, repos, today):
    rows = sorted(((r["repository"]["name"], r["contributions"]["totalCount"]) for r in repos if not r["repository"]["isPrivate"]), key=lambda r: -r[1])
    y0 = 70
    row_h = 30
    y1 = y0 + 14 + row_h * max(len(rows), 1)
    bar_x, bar_max = 400, 720
    top = max((n for _, n in rows), default=1)
    body = ""
    for i, (name, n) in enumerate(rows):
        y = y0 + 12 + i * row_h
        width = max(2, bar_max * n / top)
        body += label(bar_x - 14, y + 15, name, "ax", "end", f'style="font-size:14px;fill:{TEXT}"')
        body += f'<rect x="{bar_x}" y="{y + 2}" width="{width:.1f}" height="18" fill="{AMBER}" fill-opacity="{0.35 + 0.65 * n / top:.2f}"/>'
        body += label(bar_x + width + 10, y + 16, str(n), "lab", "start", 'style="font-size:14px"')
    total = sum(n for _, n in rows)
    card(path, kick="LIVE SIGNAL", title="Commits by project", right=f"UPDATED {today:%Y-%m-%d}",
         desc=[f"{total} commits to public repositories in the last year."], tags="",
         body=body, w=1224, h=y1 + 62, plot=(24, y0, 1200, y1))


def languages_card(path, repos, today):
    sizes = {}
    for repo in repos:
        for edge in repo["languages"]["edges"]:
            sizes[edge["node"]["name"]] = sizes.get(edge["node"]["name"], 0) + edge["size"]
    total = sum(sizes.values()) or 1
    x0, y0, x1, y1 = 20, 68, 475, 180
    rows = sorted(sizes.items(), key=lambda item: -item[1])[:4]
    bar_x, bar_max = 122, 280
    body = ""
    for i, (name, size) in enumerate(rows):
        y = y0 + 7 + i * 26
        share = size / total
        width = max(2, bar_max * share)
        body += label(bar_x - 10, y + 13, name, "ax", "end", f'style="font-size:13px;fill:{TEXT}"')
        body += f'<rect x="{bar_x}" y="{y + 1}" width="{width:.1f}" height="16" fill="{AMBER}" fill-opacity="{0.35 + 0.65 * share:.2f}"/>'
        body += label(bar_x + width + 8, y + 14, f"{share * 100:.1f}%", "lab", "start")
    card(path, kick="LIVE SIGNAL", title="Languages by bytes", title_size=20, right=f"{today:%Y-%m-%d}", desc=[], tags="",
         body=body, w=495, h=195, plot=(x0, y0, x1, y1))


def main(user, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    user_data = fetch(user)
    data = user_data["contributionsCollection"]
    today = dt.datetime.now(dt.timezone.utc).date()
    spectrum_card(out / "signal-spectrum.svg", data["contributionCalendar"], today)
    composition_card(out / "signal-commits.svg", data["commitContributionsByRepository"], today)
    languages_card(out / "signal-languages.svg", user_data["repositories"]["nodes"], today)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
